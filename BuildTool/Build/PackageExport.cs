using System.Text;

namespace Beast.BuildTool;

/// <summary>What another build system needs to use an installed library target.</summary>
public sealed record ExportInfo(string Name, TargetType Type, PlatformType Platform, string Version, string CppStandard,
    List<string> Definitions, List<string> LinkLibraries, List<string> DependencyTargets)
{
    internal static ExportInfo Create(ProjectModel model, BuildTarget target, Platform platform, LinkEnvironment link)
    {
        var own = model.OwnModules(target).ToHashSet();
        var definitions = new List<string>();
        // Public definitions and export macros of the modules this target compiles, as consumers see them.
        foreach (var module in own.SelectMany(m => model.PublicClosure(m)).Distinct().Where(own.Contains))
        {
            definitions.AddRange(module.PublicDefinitions);
            if (ProjectModel.ApiMacroName(module) is { } macro)
                definitions.Add(macro + "=" + (target.Rules.Type == TargetType.SharedLibrary && platform.Type == PlatformType.Windows ? "__declspec(dllimport)" : ""));
        }
        // A static library does not carry its external libraries: consumers link them.
        var libraries = new List<string>();
        var dependencies = new List<string>();
        if (target.Rules.Type == TargetType.StaticLibrary)
        {
            foreach (string library in link.InputLibraries)
            {
                string value = platform.Type == PlatformType.Windows && library.EndsWith(".lib", StringComparison.OrdinalIgnoreCase) && library.IndexOfAny(['/', '\\']) < 0
                    ? library[..^4] : library;
                if (!libraries.Contains(value)) libraries.Add(value);
            }
            dependencies.AddRange(model.LinkedTargets(target).Select(t => t.Name));
        }
        string standard = target.Rules.CppVersion switch { CppVersion.Cpp14 => "14", CppVersion.Cpp17 => "17", CppVersion.Latest => "23", _ => "20" };
        return new(target.Name, target.Rules.Type, platform.Type, target.Rules.Version, standard, definitions.Distinct().ToList(), libraries, dependencies);
    }
}

/// <summary>
/// install writes CMake package files (lib/cmake/&lt;Target&gt;/&lt;Target&gt;Config.cmake, imported target
/// &lt;Target&gt;::&lt;Target&gt;) and pkg-config files (lib/pkgconfig/&lt;Target&gt;.pc) for library targets.
/// Both are relocatable: paths are relative to the files themselves.
/// </summary>
public static class PackageExport
{
    public static List<string> Write(string prefix, ExportInfo export, string libraryFile, string? importLibrary)
    {
        var written = new List<string>();
        string cmakeDirectory = Path.Combine(prefix, "lib", "cmake", export.Name);
        Directory.CreateDirectory(cmakeDirectory);
        string config = Path.Combine(cmakeDirectory, export.Name + "Config.cmake");
        File.WriteAllText(config, CMakeConfig(export, libraryFile, importLibrary));
        written.Add(config);
        if (export.Version.Length > 0)
        {
            string version = Path.Combine(cmakeDirectory, export.Name + "ConfigVersion.cmake");
            File.WriteAllText(version, CMakeVersion(export.Version));
            written.Add(version);
        }
        if (export.Platform != PlatformType.Windows)
        {
            string pkgconfig = Path.Combine(prefix, "lib", "pkgconfig", export.Name + ".pc");
            Directory.CreateDirectory(Path.GetDirectoryName(pkgconfig)!);
            File.WriteAllText(pkgconfig, PkgConfig(export, libraryFile));
            written.Add(pkgconfig);
        }
        return written;
    }

    /// <summary>
    /// Library location as written by install: lib/&lt;file&gt; (bin/ for a DLL); Android packages
    /// select lib/${ANDROID_ABI}/&lt;file&gt; in CMake and lib/&lt;abi&gt; in pkg-config.
    /// </summary>
    private static string Location(ExportInfo export, string file) => export.Platform switch
    {
        PlatformType.Android => "${_beast_prefix}/lib/${CMAKE_ANDROID_ARCH_ABI}/" + file,
        PlatformType.Windows when file.EndsWith(".dll", StringComparison.OrdinalIgnoreCase) => "${_beast_prefix}/bin/" + file,
        _ => "${_beast_prefix}/lib/" + file
    };

    internal static string CMakeConfig(ExportInfo export, string libraryFile, string? importLibrary)
    {
        string name = export.Name, imported = name + "::" + name;
        var text = new StringBuilder();
        text.AppendLine($"# Generated by Beast for target {name} ({export.Type}, {export.Platform}). Do not edit.");
        text.AppendLine("# Usage: find_package(" + name + " CONFIG REQUIRED) and target_link_libraries(app PRIVATE " + imported + ").");
        text.AppendLine("cmake_minimum_required(VERSION 3.16)");
        text.AppendLine("get_filename_component(_beast_prefix \"${CMAKE_CURRENT_LIST_DIR}/../../..\" ABSOLUTE)");
        if (export.DependencyTargets.Count > 0)
        {
            text.AppendLine("include(CMakeFindDependencyMacro)");
            foreach (string dependency in export.DependencyTargets) text.AppendLine($"find_dependency({dependency} CONFIG)");
        }
        text.AppendLine($"if(NOT TARGET {imported})");
        text.AppendLine($"  add_library({imported} {(export.Type == TargetType.SharedLibrary ? "SHARED" : "STATIC")} IMPORTED)");
        text.AppendLine($"  set_target_properties({imported} PROPERTIES");
        text.AppendLine($"    IMPORTED_LOCATION \"{Location(export, libraryFile)}\"");
        if (importLibrary != null) text.AppendLine($"    IMPORTED_IMPLIB \"${{_beast_prefix}}/lib/{importLibrary}\"");
        if (export.Type == TargetType.SharedLibrary && export.Platform is PlatformType.Linux or PlatformType.Android)
            text.AppendLine($"    IMPORTED_SONAME \"{libraryFile}\"");
        text.AppendLine("    INTERFACE_INCLUDE_DIRECTORIES \"${_beast_prefix}/include\"");
        text.AppendLine($"    INTERFACE_COMPILE_FEATURES \"cxx_std_{export.CppStandard}\"");
        if (export.Definitions.Count > 0)
            text.AppendLine($"    INTERFACE_COMPILE_DEFINITIONS \"{string.Join(";", export.Definitions.Select(CMakeEscape))}\"");
        var links = export.DependencyTargets.Select(d => d + "::" + d).Concat(export.LinkLibraries.Select(CMakeLinkItem)).ToList();
        if (links.Count > 0) text.AppendLine($"    INTERFACE_LINK_LIBRARIES \"{string.Join(";", links.Select(CMakeEscape))}\"");
        text.AppendLine("  )");
        text.AppendLine("endif()");
        text.AppendLine("unset(_beast_prefix)");
        text.AppendLine($"set({name}_FOUND TRUE)");
        return text.ToString();
    }

    /// <summary>"pthread" stays a name, "-pthread" an option; "-framework Cocoa" becomes CMake's "-framework Cocoa" form.</summary>
    private static string CMakeLinkItem(string library) => library.StartsWith("-framework ", StringComparison.Ordinal)
        ? "-framework " + library["-framework ".Length..].Trim() : library;

    private static string CMakeEscape(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("$", "\\$").Replace(";", "\\;");

    internal static string CMakeVersion(string version) => $$"""
        # Generated by Beast. Compatible: same major version, not older.
        set(PACKAGE_VERSION "{{version}}")
        if(PACKAGE_FIND_VERSION)
          string(REGEX MATCH "^[0-9]+" _beast_major "${PACKAGE_VERSION}")
          if(PACKAGE_FIND_VERSION VERSION_GREATER PACKAGE_VERSION OR NOT PACKAGE_FIND_VERSION_MAJOR STREQUAL _beast_major)
            set(PACKAGE_VERSION_COMPATIBLE FALSE)
          else()
            set(PACKAGE_VERSION_COMPATIBLE TRUE)
            if(PACKAGE_FIND_VERSION STREQUAL PACKAGE_VERSION)
              set(PACKAGE_VERSION_EXACT TRUE)
            endif()
          endif()
          unset(_beast_major)
        else()
          set(PACKAGE_VERSION_COMPATIBLE TRUE)
        endif()

        """;

    internal static string PkgConfig(ExportInfo export, string libraryFile)
    {
        var cflags = new List<string> { "-I${includedir}", "-std=c++" + export.CppStandard };
        cflags.AddRange(export.Definitions.Select(d => "-D" + PkgEscape(d)));
        bool named = libraryFile.StartsWith("lib", StringComparison.Ordinal) && Path.GetExtension(libraryFile) is ".a" or ".so" or ".dylib";
        var libs = new List<string> { "-L${libdir}", named ? "-l" + Path.GetFileNameWithoutExtension(libraryFile)[3..] : "${libdir}/" + libraryFile };
        // Programs linked against the shared library find it without LD_LIBRARY_PATH/DYLD paths.
        if (export.Type == TargetType.SharedLibrary && export.Platform != PlatformType.Android) libs.Add("-Wl,-rpath,${libdir}");
        libs.AddRange(export.LinkLibraries.Select(l => l.StartsWith('-') ? l : l.IndexOfAny(['/', '\\']) >= 0 ? PkgEscape(l) : "-l" + l));
        var text = new StringBuilder();
        text.AppendLine($"# Generated by Beast for target {export.Name} ({export.Type}, {export.Platform}). Do not edit.");
        text.AppendLine("prefix=${pcfiledir}/../..");
        if (export.Platform == PlatformType.Android)
        {
            // pkg-config --define-variable=abi=x86_64 selects another ABI.
            text.AppendLine("abi=arm64-v8a");
            text.AppendLine("libdir=${prefix}/lib/${abi}");
        }
        else text.AppendLine("libdir=${prefix}/lib");
        text.AppendLine("includedir=${prefix}/include");
        text.AppendLine();
        text.AppendLine($"Name: {export.Name}");
        text.AppendLine($"Description: {export.Name} ({export.Type}, built by Beast)");
        text.AppendLine($"Version: {(export.Version.Length > 0 ? export.Version : "0")}");
        if (export.DependencyTargets.Count > 0) text.AppendLine("Requires: " + string.Join(", ", export.DependencyTargets));
        text.AppendLine("Cflags: " + string.Join(' ', cflags));
        text.AppendLine("Libs: " + string.Join(' ', libs));
        return text.ToString();
    }

    /// <summary>pkg-config splits fields like a shell: escape quotes, spaces, parentheses and backslashes.</summary>
    private static string PkgEscape(string value)
    {
        var result = new StringBuilder();
        foreach (char c in value)
        {
            if (c is '"' or '\'' or ' ' or '(' or ')' or '\\' or '$' or '#' or '&' or ';' or '<' or '>' or '|') result.Append('\\');
            result.Append(c);
        }
        return result.ToString();
    }
}
