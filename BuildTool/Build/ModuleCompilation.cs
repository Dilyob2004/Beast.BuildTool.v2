using System.Text;

namespace Beast.BuildTool;

/// <summary>Opt-in module-local compilation transformations. Never writes into Source.</summary>
public static class ModuleCompilation
{
    public static void WriteIfChanged(string path, string text)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        if (!File.Exists(path) || File.ReadAllText(path) != text) File.WriteAllText(path, text, new UTF8Encoding(false));
    }

    public static List<string> Prepare(ModuleRules module, CPPEnvironment environment, List<string> sources, string generatedPath, ISet<string>? generatedOutputs = null)
    {
        HashSet<string> Exclusions(IEnumerable<string> paths, string setting)
        {
            var resolved = paths.Select(p => ProjectModel.ResolvePath(module, p)).ToHashSet(StringComparer.OrdinalIgnoreCase);
            // A file skipped for this platform or by ExcludedSources may still be named here.
            bool FilteredOut(string path) => File.Exists(path) &&
                path.StartsWith(module.ModuleDirectory + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase) &&
                SourceFilter.IsCompilable(path);
            foreach (string path in resolved)
                if (!sources.Contains(path, StringComparer.OrdinalIgnoreCase) && !FilteredOut(path))
                    throw new InvalidOperationException($"{module.ModuleName}: {setting} names a source not owned by this module: {path}");
            return resolved;
        }
        environment.PrecompiledHeaderExcludedFiles.UnionWith(Exclusions(module.PrecompiledHeaderExcludedFiles, nameof(module.PrecompiledHeaderExcludedFiles)));
        if (!string.IsNullOrWhiteSpace(module.PrecompiledHeaderSource))
        {
            environment.PrecompiledHeaderSource = ProjectModel.ResolvePath(module, module.PrecompiledHeaderSource);
            if (sources.Contains(environment.PrecompiledHeaderSource, StringComparer.OrdinalIgnoreCase))
                throw new InvalidOperationException($"{module.ModuleName}: PrecompiledHeaderSource must be a header, not a compiled source.");
            if (!File.Exists(environment.PrecompiledHeaderSource) && generatedOutputs?.Contains(environment.PrecompiledHeaderSource) != true)
                throw new FileNotFoundException($"{module.ModuleName}: PCH header not found", environment.PrecompiledHeaderSource);
            environment.PrecompiledHeaderUsage = PrecompiledHeaderFileUsage.CreateManual;
        }
        if (!module.UseUnityBuild) return sources;
        if (module.UnityBatchSize < 2 || module.UnityBatchSize > 64)
            throw new InvalidOperationException($"{module.ModuleName}: UnityBatchSize must be between 2 and 64.");
        var excluded = Exclusions(module.UnityExcludedFiles, nameof(module.UnityExcludedFiles));
        excluded.UnionWith(environment.PrecompiledHeaderExcludedFiles);
        var standalone = sources.Where(p => Path.GetExtension(p).Equals(".c", StringComparison.OrdinalIgnoreCase) || SourceFilter.IsAssembly(p) || SourceFilter.IsObjectiveC(p) || environment.ModuleUnits.ContainsKey(p) || excluded.Contains(p)).ToList();
        var grouped = sources.Except(standalone, StringComparer.OrdinalIgnoreCase).Order(StringComparer.OrdinalIgnoreCase).Chunk(module.UnityBatchSize);
        int index = 0;
        foreach (var group in grouped)
        {
            if (group.Length == 1) { standalone.Add(group[0]); continue; }
            string unit = Path.Combine(generatedPath, $"Unity_{index++:D4}.cpp");
            WriteIfChanged(unit, "// Generated by Beast; edit original source files.\n" + string.Join("\n", group.Select(p => $"#include \"{p.Replace('\\', '/')}\"")) + "\n");
            environment.SourcePrerequisites.Add(unit, group.ToList());
            standalone.Add(unit);
        }
        return standalone;
    }

    public static bool UsesPch(CPPEnvironment environment, string source) =>
        environment.PrecompiledHeaderUsage != PrecompiledHeaderFileUsage.None &&
        !Path.GetExtension(source).Equals(".c", StringComparison.OrdinalIgnoreCase) && !SourceFilter.IsAssembly(source) && !SourceFilter.IsObjectiveC(source) &&
        // A PCH cannot be combined with module declarations or imports.
        !environment.ModuleUnits.ContainsKey(source) && !environment.PrecompiledHeaderExcludedFiles.Contains(source);
}
